/**
 * @file The code scaffold (work document #29): the deterministic starting
 * point "Implement in code" writes into the component's collaborative
 * buffer. Deterministic per component name — the implementation flow
 * derives the ladder's honesty from it: a buffer equal to the scaffold is
 * still a stub; only authored code leaves the sketch.
 *
 * @param {string} componentName
 * @returns {string}
 */
export function codeScaffold(componentName) {
  return `// ${componentName} — implemented in code (work document #29)\n// Replace this scaffold with the component's implementation. The ports\n// follow the declared signature.\nexport default function setup(runtime) {\n  // Register port handlers here.\n}\n`;
}
