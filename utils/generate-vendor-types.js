/**
 * @file Vendor type generation for packages that ship no declarations but
 * carry good JSDoc (work document #24): the declarations are emitted
 * locally from the packages' own sources with `tsc --declaration
 * --emitDeclarationOnly`, so the vendor type surface needs nothing from
 * upstream releases. Packages that ship their own declarations instead flow
 * through the type-only tsdown builds (utils/*-types-entry.js), and noflo's
 * declaration graph (which defeats rolldown-plugin-dts) gets a generated
 * re-export shim.
 *
 * Output: `vendor/types/<pkg>/*.d.ts` plus a thin re-export shim
 * `vendor/<pkg>.d.ts`, so first-party imports of `vendor/<pkg>.js` resolve
 * to generated declarations. External package references inside the
 * generated declarations (e.g. `@reticulum/core`) resolve through
 * node_modules and converge with the sibling vendor shims, which re-export
 * the same package types.
 */

import { execFileSync } from "node:child_process";
import {
  cpSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");

/**
 * Re-export shims for packages whose own declarations are shipped but whose
 * declaration graphs defeat rolldown-plugin-dts (noflo: the noflo →
 * fbp-graph graph silently emits `export {}` through the type-only tsdown
 * build, work document #24). Plain re-export shims sidestep the bundler:
 * TypeScript resolves the package's own declarations natively, and the
 * vendor-path imports resolve to the same types.
 *
 * @type {Array<{ name: string, body: string }>}
 */
const shims = [
  {
    name: "noflo",
    // The explicit declaration-file path sidesteps noflo's exports map,
    // which resolves to the JS source under bundler resolution and drops
    // the named-export surface; the sibling lib/NoFlo.d.ts carries it
    body: 'export * from "../node_modules/noflo/lib/NoFlo.js";\nexport { default } from "../node_modules/noflo/lib/NoFlo.js";\n',
  },
  {
    // The QR encoder ships no types: the shim types the surface the
    // application uses — SVG string rendering for invites and connection
    // URIs (work document #28 update #3)
    name: "qrcode",
    body: [
      "declare const QRCode: {",
      "  /** Renders text as an SVG document string */",
      "  toString(",
      "    text: string,",
      "    options?: {",
      '      type?: "svg" | "utf8" | "terminal";',
      "      margin?: number;",
      "      width?: number;",
      "    },",
      "  ): Promise<string>;",
      "};",
      "export default QRCode;",
      "",
    ].join("\n"),
  },
];

for (const shim of shims) {
  writeFileSync(
    resolve(root, `vendor/${shim.name}.d.ts`),
    `// Generated by utils/generate-vendor-types.js — do not edit.\n${shim.body}`,
  );
  console.log(`Generated the ${shim.name} re-export shim`);
}

/**
 * Resolves an export specifier from a vendor entry to the package source
 * module it names, relative to `node_modules`: relative specifiers point
 * into node_modules directly; a bare package specifier resolves to the
 * package's source index.
 *
 * @param {string} specifier
 * @returns {string} Path relative to node_modules.
 */
function sourceModuleFor(specifier) {
  const inNodeModules = specifier.replace(
    /^(?:\.\.\/)+node_modules\//,
    "",
  );
  if (/\.[cm]?js$/.test(inNodeModules)) return inNodeModules;
  // Bare package specifier: the package's source index
  return `${inNodeModules}/src/index.js`;
}

/**
 * The packages generated from JSDoc sources. `surfaceEntry` is the
 * first-party vendor entry whose `export ... from "..."` statements define
 * exactly the surface the runtime bundle carries: the generator mirrors it
 * so the declarations cannot drift from the bundle.
 *
 * @type {Array<{ name: string, surfaceEntry: string, outDir: string }>}
 */
const generated = [
  {
    name: "dacar",
    surfaceEntry: "utils/dacar-entry.js",
    outDir: "vendor/types/dacar",
  },
];

for (const pkg of generated) {
  const entrySource = readFileSync(resolve(root, pkg.surfaceEntry), "utf8");
  /** @type {string[]} */
  const modules = [];
  const exportRe =
    /export\s+(?:\*\s+from|\{[^}]*\}\s+from)\s*["']([^"']+)["']/g;
  for (const match of entrySource.matchAll(exportRe)) {
    const modulePath = sourceModuleFor(match[1]);
    if (!modules.includes(modulePath)) modules.push(modulePath);
  }
  if (modules.length === 0) {
    throw new Error(`No export statements found in ${pkg.surfaceEntry}`);
  }

  // Stage the package sources outside node_modules: TypeScript's declaration
  // emit drops the re-export statements of modules living under
  // node_modules (observed with tsc 6, no error raised), so the sources are
  // copied to a staging directory and emitted from there. The staged copy
  // keeps the package's module layout, so the relative imports between the
  // modules still resolve, and it stays inside the repository so the
  // packages' type references resolve through the project's node_modules.
  const packageRoots = [
    ...new Set(
      modules.map((modulePath) =>
        modulePath.split("/").slice(0, modulePath.startsWith("@") ? 2 : 1).join("/"),
      ),
    ),
  ];
  const staging = resolve(root, ".vendor-types-staging");
  rmSync(staging, { recursive: true, force: true });
  try {
    for (const packageRoot of packageRoots) {
      cpSync(
        resolve(root, "node_modules", packageRoot, "src"),
        resolve(staging, packageRoot, "src"),
        { recursive: true },
      );
    }

    const sourceFiles = modules.map((modulePath) =>
      resolve(staging, modulePath),
    );
    // tsc emits the declaration tree relative to the sources' common root
    const isWithin = (/** @type {string} */ path, /** @type {string} */ dir) =>
      path === dir || path.startsWith(`${dir}/`);
    const sourceDirs = sourceFiles.map((file) => resolve(file, ".."));
    let commonRoot = sourceDirs[0];
    for (const dir of sourceDirs) {
      while (
        !isWithin(dir, commonRoot) &&
        !isWithin(commonRoot, dir) &&
        commonRoot !== resolve(commonRoot, "..")
      ) {
        commonRoot = resolve(commonRoot, "..");
      }
    }

    rmSync(resolve(root, pkg.outDir), { recursive: true, force: true });
    mkdirSync(resolve(root, pkg.outDir), { recursive: true });
    execFileSync(
      resolve(root, "node_modules/.bin/tsc"),
      [
        ...sourceFiles,
        "--allowJs",
        "--declaration",
        "--emitDeclarationOnly",
        "--module",
        "esnext",
        "--moduleResolution",
        "bundler",
        "--target",
        "es2022",
        "--skipLibCheck",
        "--ignoreConfig",
        "--outDir",
        resolve(root, pkg.outDir),
      ],
      { stdio: "inherit" },
    );

    // The thin re-export shim: one block per entry export, pointing at the
    // emitted declaration relative to vendor/<name>.d.ts. Modules whose
    // entry re-exports a default get the default carried over too —
    // `export *` does not re-export defaults (qrcode's browser surface is
    // default-only)
    const shimLines = modules.flatMap((modulePath) => {
      const emitted = relative(
        resolve(root, "vendor"),
        resolve(
          root,
          pkg.outDir,
          relative(commonRoot, resolve(staging, modulePath)),
        ),
      ).replaceAll("\\", "/");
      const from = `from "./${emitted}"`;
      const lines = [`export * ${from};`];
      // The entry's own specifier, resolved back from the staged module
      // path: the shim carries a default re-export only when the entry
      // exports one from that module
      const entrySpecifier = `../node_modules/${modulePath}`;
      if (
        new RegExp(
          `export\\s+\\{[^}]*default[^}]*\\}\\s+from\\s+["']${entrySpecifier.replaceAll("/", "\\/")}["']`,
        ).test(entrySource)
      ) {
        lines.push(`export { default } ${from};`);
      }
      return lines;
    });
    writeFileSync(
      resolve(root, `vendor/${pkg.name}.d.ts`),
      `// Generated by utils/generate-vendor-types.js — do not edit.\n// Declarations emitted from the package's JSDoc sources, mirroring the\n// vendor entry's surface (work document #24).\n${shimLines.join("\n")}\n`,
    );
    console.log(`Generated vendor types for ${pkg.name}`);
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }
}