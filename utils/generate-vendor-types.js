/**
 * @file Vendor type generation for packages whose declaration graphs defeat
 * the bundler-based pipeline (work document #24): noflo ships per-module
 * declarations, but its noflo → fbp-graph declaration graph silently emits
 * `export {}` through the type-only tsdown build. A plain re-export shim
 * sidesteps the bundler: TypeScript resolves the package's own declarations
 * natively, and the vendor-path imports resolve to the same types. (The
 * shim's explicit declaration-file path bypasses noflo's exports map, which
 * would otherwise resolve to the JS source and drop the named-export
 * surface under bundler resolution.)
 *
 * Packages that ship resolvable declarations flow through the type-only
 * tsdown builds (utils/*-types-entry.js) instead.
 */

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");

/**
 * Re-export shims emitted as `vendor/<name>.d.ts`.
 *
 * @type {Array<{ name: string, body: string }>}
 */
const shims = [
  {
    name: "noflo",
    body: 'export * from "../node_modules/noflo/lib/NoFlo.js";\nexport { default } from "../node_modules/noflo/lib/NoFlo.js";\n',
  },
];

for (const shim of shims) {
  writeFileSync(
    resolve(root, `vendor/${shim.name}.d.ts`),
    `// Generated by utils/generate-vendor-types.js — do not edit.\n${shim.body}`,
  );
  console.log(`Generated the ${shim.name} re-export shim`);
}
