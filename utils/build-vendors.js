/**
 * @file Vendor builds (SPEC "Build/Vendoring Mechanics"): the bundler is
 * used strictly to flatten and export external dependencies into single ES
 * module files inside `vendor/`, so the live application itself runs
 * natively via import maps and native ESM — no build step for first-party
 * code. Run this only when a dependency is added or updated: vendor outputs
 * are committed, and `git diff` on rebuilds shows what a bump changed.
 *
 * The bundler is esbuild. The vendor contract it implements:
 *
 * - Vendor file names are unversioned so first-party imports and import
 *   maps stay stable across dependency bumps.
 * - One module per package: packages that must share one instance across
 *   contexts (yjs, @reticulum/core) are never inlined into their consumers;
 *   the sibling-external plugin below keeps them external and rewrites
 *   their specifiers to the relative sibling paths (`./yjs.js`,
 *   `./reticulum-core.js`) the import maps resolve.
 * - Everything else is inlined: import maps cannot resolve nested bare
 *   specifiers inside third-party modules.
 * - Banner-injected code is prepended to the output verbatim: the
 *   reticulum-core crypto import shadows the global so browsers without
 *   native X25519 (WebKit) can run the full stack.
 * - NoFlo 2.x is native ESM with no Node builtins, so its bundle carries no
 *   shims or stubs; components from @noflo/core are vendored per component
 *   (the publish-time manifest shape), not as a package monolith.
 *
 * Type declarations are generated, not hand-written — see
 * utils/generate-vendor-types.js.
 */

