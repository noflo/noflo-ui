/**
 * Escapes a package name for literal use in an esbuild onResolve filter.
 *
 * @param {string} name
 * @returns {string}
 */
function escapeFilter(name) {
  return name.replace(/[\\^$.|?*+()[{]/g, "\\$&");
}

/**
 * Marks sibling vendor bundles external and rewrites their specifiers to
 * relative sibling paths. esbuild emits the path returned by `onResolve`
 * verbatim for external modules, which reproduces the specifier rewriting
 * the previous bundler did with its output `paths` option: consumers of the
 * vendored module must all receive the same shared instance, served as the
 * sibling vendor bundle. Subpath imports of an external package (the lxmf
 * stamper deep-imports `@reticulum/core/src/utils/stamper.js`) rewrite to
 * the sibling too — it re-exports the same surface.
 *
 * @param {Record<string, string>} siblings Package name to sibling path.
 * @returns {esbuild.Plugin}
 */
function siblingExternals(siblings) {
  const filter = new RegExp(
    `^(?:${Object.keys(siblings).map(escapeFilter).join("|")})(?:/.*)?$`,
  );
  return {
    name: "vendor-siblings",
    setup(build) {
      build.onResolve({ filter }, (args) => {
        const segments = args.path.split("/");
        const name = segments[0].startsWith("@")
          ? segments.slice(0, 2).join("/")
          : segments[0];
        return { path: siblings[name], external: true };
      });
    },
  };
}

